// Code d'erreur (SQL, Supabase Auth ou réseau) → message lisible.
export function errorText(t, err) {
  const code = err?.code || err?.message || ''
  if (t.errors[code]) return t.errors[code]
  if (/captcha/i.test(code)) return t.errors.captcha_failed
  if (/fetch|network/i.test(code)) return t.errors.network
  return t.errors.generic
}

